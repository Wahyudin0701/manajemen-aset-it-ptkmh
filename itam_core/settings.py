# Tambahkan origin otomatis untuk akses LAN jika DEBUG=True
if DEBUG:
    for default_origin in ['http://localhost:8000', 'http://127.0.0.1:8000', 'http://0.0.0.0:8000']:
        if default_origin not in CSRF_TRUSTED_ORIGINS:
            CSRF_TRUSTED_ORIGINS.append(default_origin)

    try:
        import socket
        hostname = socket.gethostname()
        local_ips = socket.gethostbyname_ex(hostname)[2]
        for ip in local_ips:
            origin_ip = f"http://{ip}:8000"
            if origin_ip not in CSRF_TRUSTED_ORIGINS:
                CSRF_TRUSTED_ORIGINS.append(origin_ip)
    except Exception:
        pass

